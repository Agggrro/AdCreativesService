    chain: "ЦЕПОЧКА ОБЁРТОК",
    features: "ВОЗМОЖНОСТИ",
    interactive: "ИНТЕРАКТИВНЫЕ СТАНДАРТЫ",
    findings: "НАХОДКИ",
    trackers: "ТРЕКИНГ",
    recommendations: "РЕКОМЕНДАЦИИ",
    noFindings: "Нарушений не найдено.",
