/**
 * Reading and writing `runtime/manifest.ts` — shared by `npm run runtime:push`
 * and the one-off `npm run runtime:migrate` (ADR-0029), so the file has one
 * shape and one header however it was produced.
 */
import { existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const MANIFEST_PATH = join(root, "runtime", "manifest.ts");

/** Kept in step with the hand-written header in runtime/manifest.ts. */
const MANIFEST_HEADER = `// GENERATED by \`npm run runtime:push\` — do not edit by hand.
//
// Maps the logical runtime keys stored in \`templates.runtime_keys\` to the
// content-addressed objects that actually hold the bytes (ADR-0017): R2, served
// from the media host (ADR-0029). Committed on purpose: the app and the ad Worker
// read it at build time, so resolving a unit URL costs no network call on the ad
// path.
//
// TypeScript rather than JSON so it loads identically under the Next bundler and
// under plain \`node\` (which demands an import attribute for JSON), and so the
// shape is type-checked.

export interface RuntimeManifest {
  generatedAt: string | null;
  assets: Record<string, { url: string; sha256: string }>;
}
`;

/** The recorded assets, or `{}` when there is no manifest yet. */
export async function readManifestAssets() {
  if (!existsSync(MANIFEST_PATH)) return {};
  // Imported rather than parsed — Node strips the types itself, and it keeps one
  // definition of the file's shape instead of a parser here and a type there.
  const existing = await import(`${pathToFileURL(MANIFEST_PATH).href}?t=${Date.now()}`);
  return { ...(existing.RUNTIME_MANIFEST?.assets ?? {}) };
}

export function writeManifest(assets) {
  // Keys sorted so a re-push produces a byte-identical file when nothing changed,
  // and a diff that shows only what moved when something did.
  const sorted = Object.fromEntries(
    Object.entries(assets).sort(([a], [b]) => a.localeCompare(b)),
  );
  const manifest = { generatedAt: new Date().toISOString(), assets: sorted };
  writeFileSync(
    MANIFEST_PATH,
    `${MANIFEST_HEADER}\nexport const RUNTIME_MANIFEST: RuntimeManifest = ${JSON.stringify(
      manifest,
      null,
      2,
    )};\n`,
  );
}

/** `a/b/unit.js` + hash -> `runtime/a/b/unit.<hash8>.js` */
export function hashedObjectKey(logicalKey, sha256) {
  const dot = logicalKey.lastIndexOf(".");
  const stem = logicalKey.slice(0, dot);
  const ext = logicalKey.slice(dot);
  return `runtime/${stem}.${sha256.slice(0, 8)}${ext}`;
}

export const CONTENT_TYPE = {
  ".js": "application/javascript",
  ".html": "text/html",
};

export function contentTypeFor(key) {
  return CONTENT_TYPE[key.slice(key.lastIndexOf("."))] ?? "application/octet-stream";
}
